package net.yozmnews.event.domain.event;

/**
 * 장기 검색용 사건 중심 인덱스 — 닫힌 사건에 모델 버전마다 HNSW 식 · 부분 인덱스를 둔다 · docs/specs/event.md §4 · event-R13.
 * <p>
 * 차원 없는 중심 컬럼에는 모델 버전마다 차원을 정한 식으로만 인덱스를 걸 수 있어, 모델 버전이 생기는 대로 실행 중에 만든다. 기사 표현에는
 * 인덱스를 두지 않는다. 열린 사건의 배정은 인덱스 없는 정확 검색이다.
 */
public interface LongTermIndexes {

	/**
	 * 닫힌 사건이 있는 모델 버전마다 인덱스가 없으면 만든다 — 트랜잭션 밖에서 부른다(동시 생성). 한 모델 버전의 닫힌 사건 차원이 하나가 아니면
	 * 만들지 않고 경고한다. 생성이 실패하면 경고하고 다음 모델 버전으로 간다.
	 * @return 만든 인덱스 수
	 */
	int ensure();

}
